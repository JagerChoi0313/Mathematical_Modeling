function export_results( ...
    simulation, ...
    gameResult, ...
    validation, ...
    data, ...
    projectRoot)
%EXPORT_RESULTS 导出第三问计算结果

outputDir = fullfile( ...
    projectRoot, ...
    'output', ...
    sprintf('case%d', data.caseID));

if ~isfolder(outputDir)
    mkdir(outputDir);
end


summaryFile = fullfile( ...
    outputDir, ...
    sprintf('case%d_summary.xlsx', data.caseID));


playerID = (1:data.numPlayers)';
initialWater = zeros(data.numPlayers, 1);
initialFood = zeros(data.numPlayers, 1);
arrivalDay = zeros(data.numPlayers, 1);
mineDays = zeros(data.numPlayers, 1);
finalWealth = zeros(data.numPlayers, 1);

for i = 1:data.numPlayers

    P = simulation.players(i);

    initialWater(i) = P.initialWater;
    initialFood(i) = P.initialFood;
    arrivalDay(i) = P.arrivalDay;
    mineDays(i) = P.mineDays;
    finalWealth(i) = P.finalWealth;

end


summaryTable = table( ...
    playerID, ...
    initialWater, ...
    initialFood, ...
    arrivalDay, ...
    mineDays, ...
    finalWealth, ...
    'VariableNames', { ...
    'Player', ...
    'InitialWater', ...
    'InitialFood', ...
    'ArrivalDay', ...
    'MineDays', ...
    'FinalWealth'});

writetable(summaryTable, ...
    summaryFile, ...
    'Sheet', 'Summary');


for i = 1:data.numPlayers

    P = simulation.players(i);

    day = (0:data.deadline)';
    region = P.region';
    water = P.water';
    food = P.food';
    cash = P.cash';

    loadKg = ...
        data.waterWeight * water + ...
        data.foodWeight * food;

    action = strings(data.deadline + 1, 1);
    action(1) = "初始购买";

    for t = 1:data.deadline
        action(t + 1) = string(P.action{t});
    end

    if data.caseID == 5

        weatherName = strings(data.deadline + 1, 1);
        weatherName(1) = "第0天";

        for t = 1:data.deadline
            weatherName(t + 1) = ...
                data.weatherNames(simulation.weather(t));
        end

    else

        weatherName = strings(data.deadline + 1, 1);
        weatherName(1) = "第0天";

        for t = 1:data.deadline
            weatherName(t + 1) = ...
                data.weatherNames(simulation.weather(t));
        end

    end


    dailyTable = table( ...
        day, ...
        weatherName, ...
        region, ...
        action, ...
        water, ...
        food, ...
        cash, ...
        loadKg, ...
        'VariableNames', { ...
        'Day', ...
        'Weather', ...
        'Region', ...
        'Action', ...
        'Water', ...
        'Food', ...
        'Cash', ...
        'LoadKg'});

    playerFile = fullfile( ...
        outputDir, ...
        sprintf('case%d_player%d_daily.xlsx', ...
        data.caseID, i));

    writetable(dailyTable, playerFile);

end


history = gameResult.iterationHistory;

if ~isempty(history)

    iteration = (1:size(history, 1))';

    historyTable = array2table(history);

    historyNames = strings(1, data.numPlayers);

    for i = 1:data.numPlayers
        historyNames(i) = sprintf('Player%dWealth', i);
    end

    historyTable.Properties.VariableNames = ...
        cellstr(historyNames);

    historyTable = addvars( ...
        historyTable, ...
        iteration, ...
        'Before', 1, ...
        'NewVariableNames', 'Iteration');

    historyFile = fullfile( ...
        outputDir, ...
        sprintf('case%d_iteration_history.xlsx', ...
        data.caseID));

    writetable(historyTable, historyFile);

end


validationName = [ ...
    "负重"; ...
    "资源非负"; ...
    "现金非负"; ...
    "路线邻接"; ...
    "沙暴移动"; ...
    "截止日期"; ...
    "多人交互"];

validationPassed = [ ...
    validation.loadPassed; ...
    validation.resourcePassed; ...
    validation.cashPassed; ...
    validation.pathPassed; ...
    validation.stormPassed; ...
    validation.deadlinePassed; ...
    validation.interactionPassed];

validationTable = table( ...
    validationName, ...
    validationPassed, ...
    'VariableNames', {'CheckItem', 'Passed'});

validationFile = fullfile( ...
    outputDir, ...
    sprintf('case%d_validation.xlsx', ...
    data.caseID));

writetable(validationTable, validationFile);


if ~isempty(validation.messages)

    messageTable = table( ...
        validation.messages, ...
        'VariableNames', {'Message'});

    writetable( ...
        messageTable, ...
        validationFile, ...
        'Sheet', 'Messages');

end

end