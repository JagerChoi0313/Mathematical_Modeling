% 第二关
% =====================================================

function draw_case2(path)


figure('Position',[100 100 1100 900]);

hold on;
axis equal;
axis off;



% 第二关坐标
P=zeros(64,2);

k=1;

for r=0:7

    for c=0:7

        P(k,:)=[c+r*0.45,8-r];

        k=k+1;

    end

end



% 六边形道路结构

for i=1:64

    for j=i+1:64

        if norm(P(i,:)-P(j,:))<1.3

            plot(P([i j],1),...
                 P([i j],2),...
                 'Color',[0.8 0.83 0.88],...
                 'LineWidth',1);

        end

    end

end



% 最优路线

for i=1:length(path)-1

plot(P(path(i:i+1),1),...
     P(path(i:i+1),2),...
     'Color',[0.05 0.32 0.65],...
     'LineWidth',5);

end



scatter(P(:,1),P(:,2),60,...
    'w',...
    'filled',...
    'MarkerEdgeColor',[0.2 0.35 0.6]);



for i=1:64

text(P(i,1)+0.05,...
     P(i,2),...
     num2str(i),...
     'FontSize',9);

end



% 起点

scatter(P(1,1),P(1,2),220,...
's','filled',...
'MarkerFaceColor',[0.2 0.65 0.3]);



% 终点

scatter(P(64,1),P(64,2),220,...
'd','filled',...
'MarkerFaceColor',[0.85 0.2 0.15]);



% 矿山

for m=[30 55]

scatter(P(m,1),P(m,2),220,...
'^','filled',...
'MarkerFaceColor',[0.95 0.65 0]);

end



% 村庄

for m=[39 62]

scatter(P(m,1),P(m,2),220,...
'p','filled',...
'MarkerFaceColor',[0.45 0.2 0.7]);

end



title('第2关最优行进路线',...
'FontSize',22,...
'FontWeight','bold');


end