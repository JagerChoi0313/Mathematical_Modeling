function plot_results_case3(result, data, projectRoot)
%PLOT_RESULTS_CASE3 绘制第三关保证型策略的最不利有效情形结果

figureDir = fullfile( ...
    projectRoot, ...
    'figures', ...
    'case3');

if ~isfolder(figureDir)
    mkdir(figureDir);
end

fontName = 'Microsoft YaHei';

mapColor   = [0.76, 0.81, 0.86];
routeColor = [0.08, 0.32, 0.52];

startColor = [0.22, 0.55, 0.36];
endColor   = [0.72, 0.22, 0.18];
mineColor  = [0.78, 0.48, 0.12];

waterColor = [0.10, 0.42, 0.68];
foodColor  = [0.80, 0.38, 0.12];
moneyColor = [0.16, 0.48, 0.36];

x = data.plotX;
y = data.plotY;

daily = result.worstDaily;

travel = daily(daily.Day > 0, :);

if isempty(travel)
    return;
end

arrivalDay = max(travel.Day);

effectiveWeatherText = ...
    strjoin(string(travel.Weather), '-');


%% 第三关保证型策略执行路线

fig = figure( ...
    'Color', 'w', ...
    'Position', [70, 50, 1280, 850]);

ax = axes(fig);
hold(ax, 'on');


% 地图邻接关系
for k = 1:size(data.edges, 1)

    i = data.edges(k, 1);
    j = data.edges(k, 2);

    plot(ax, ...
        [x(i), x(j)], ...
        [y(i), y(j)], ...
        '-', ...
        'Color', mapColor, ...
        'LineWidth', 1.15);

end


% 普通区域节点
scatter(ax, ...
    x, ...
    y, ...
    46, ...
    'o', ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', [0.42, 0.50, 0.58], ...
    'LineWidth', 1.0);


% 绘制实际执行路线
for r = 1:height(travel)

    i = travel.StartRegion(r);
    j = travel.EndRegion(r);

    if i ~= j

        dx = x(j) - x(i);
        dy = y(j) - y(i);

        quiver(ax, ...
            x(i) + 0.08 * dx, ...
            y(i) + 0.08 * dy, ...
            0.84 * dx, ...
            0.84 * dy, ...
            0, ...
            'Color', routeColor, ...
            'LineWidth', 3.3, ...
            'MaxHeadSize', 0.20);

        midX = (x(i) + x(j)) / 2;
        midY = (y(i) + y(j)) / 2;

        len = hypot(dx, dy);

        if len > 0
            offsetX = -dy / len * 0.14;
            offsetY =  dx / len * 0.14;
        else
            offsetX = 0;
            offsetY = 0;
        end

        text(ax, ...
            midX + offsetX, ...
            midY + offsetY, ...
            sprintf('第%d天', travel.Day(r)), ...
            'FontName', fontName, ...
            'FontSize', 9.5, ...
            'Color', [0.18, 0.23, 0.28], ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', ...
            'BackgroundColor', 'w', ...
            'Margin', 1);

    end

end


% 路线经过的普通节点
routeNodes = unique( ...
    [travel.StartRegion; travel.EndRegion], ...
    'stable');

ordinaryRouteNodes = routeNodes( ...
    ~ismember(routeNodes, ...
    [data.startRegion, data.endRegion, data.mineRegions]));

if ~isempty(ordinaryRouteNodes)

    scatter(ax, ...
        x(ordinaryRouteNodes), ...
        y(ordinaryRouteNodes), ...
        76, ...
        'o', ...
        'MarkerFaceColor', routeColor, ...
        'MarkerEdgeColor', 'w', ...
        'LineWidth', 1.0);

end


% 起点
hStart = scatter(ax, ...
    x(data.startRegion), ...
    y(data.startRegion), ...
    155, ...
    's', ...
    'MarkerFaceColor', startColor, ...
    'MarkerEdgeColor', [0.10, 0.34, 0.19], ...
    'LineWidth', 1.4);


% 矿山
hMine = scatter(ax, ...
    x(data.mineRegions), ...
    y(data.mineRegions), ...
    155, ...
    '^', ...
    'MarkerFaceColor', mineColor, ...
    'MarkerEdgeColor', [0.52, 0.29, 0.04], ...
    'LineWidth', 1.4);


% 终点
hEnd = scatter(ax, ...
    x(data.endRegion), ...
    y(data.endRegion), ...
    165, ...
    'd', ...
    'MarkerFaceColor', endColor, ...
    'MarkerEdgeColor', [0.46, 0.10, 0.08], ...
    'LineWidth', 1.4);


hRoute = plot(ax, ...
    nan, nan, ...
    '-', ...
    'Color', routeColor, ...
    'LineWidth', 3.3);


% 节点编号
for i = 1:data.numRegions

    if i == data.startRegion

        label = sprintf('起点  %d', i);
        labelColor = startColor;
        labelWeight = 'bold';

    elseif i == data.endRegion

        label = sprintf('终点  %d', i);
        labelColor = endColor;
        labelWeight = 'bold';

    elseif ismember(i, data.mineRegions)

        label = sprintf('%d  矿山', i);
        labelColor = mineColor;
        labelWeight = 'bold';

    else

        label = num2str(i);
        labelColor = [0.20, 0.25, 0.30];
        labelWeight = 'normal';

    end

    text(ax, ...
        x(i) + 0.08, ...
        y(i) + 0.06, ...
        label, ...
        'FontName', fontName, ...
        'FontSize', 9.5, ...
        'FontWeight', labelWeight, ...
        'Color', labelColor);

end


legend(ax, ...
    [hRoute, hStart, hMine, hEnd], ...
    {'策略执行路线', '起点', '矿山', '终点'}, ...
    'FontName', fontName, ...
    'FontSize', 9.5, ...
    'Location', 'best');


title(ax, ...
    { ...
    '第三关保证型策略执行路线', ...
    sprintf( ...
    '最不利有效天气：%s；第%d天到达终点', ...
    char(effectiveWeatherText), ...
    arrivalDay) ...
    }, ...
    'FontName', fontName, ...
    'FontSize', 14, ...
    'FontWeight', 'bold', ...
    'Color', [0.12, 0.16, 0.20]);


axis(ax, 'equal');
axis(ax, 'off');

xlim(ax, ...
    [min(x)-0.55, max(x)+1.15]);

ylim(ax, ...
    [min(y)-0.55, max(y)+0.75]);

hold(ax, 'off');


exportgraphics(fig, ...
    fullfile( ...
    figureDir, ...
    'case3_worst_route.png'), ...
    'Resolution', 400);

close(fig);



%% 水和食物剩余量

fig = figure( ...
    'Color', 'w', ...
    'Position', [120, 100, 1100, 650]);

ax = axes(fig);
hold(ax, 'on');


plot(ax, ...
    daily.Day, ...
    daily.WaterLeft, ...
    '-o', ...
    'Color', waterColor, ...
    'LineWidth', 2.1, ...
    'MarkerSize', 6, ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', waterColor);


plot(ax, ...
    daily.Day, ...
    daily.FoodLeft, ...
    '-s', ...
    'Color', foodColor, ...
    'LineWidth', 2.1, ...
    'MarkerSize', 5.7, ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', foodColor);


xlabel(ax, ...
    '日期', ...
    'FontName', fontName, ...
    'FontSize', 11);


ylabel(ax, ...
    '剩余数量（箱）', ...
    'FontName', fontName, ...
    'FontSize', 11);


title(ax, ...
    { ...
    '第三关最不利有效天气下水和食物剩余量变化', ...
    sprintf('有效天气：%s', char(effectiveWeatherText)) ...
    }, ...
    'FontName', fontName, ...
    'FontSize', 14, ...
    'FontWeight', 'bold');


legend(ax, ...
    {'水', '食物'}, ...
    'FontName', fontName, ...
    'FontSize', 10, ...
    'Location', 'best');


grid(ax, 'on');
box(ax, 'off');

ax.GridColor = [0.82, 0.84, 0.86];
ax.GridAlpha = 0.45;
ax.FontName = fontName;
ax.FontSize = 10;


xticks(ax, unique(daily.Day));

xlim(ax, ...
    [min(daily.Day), max(daily.Day)]);


maxResource = max( ...
    [daily.WaterLeft; daily.FoodLeft]);

ylim(ax, ...
    [0, maxResource * 1.10 + 1]);


hold(ax, 'off');


exportgraphics(fig, ...
    fullfile( ...
    figureDir, ...
    'case3_worst_resource_change.png'), ...
    'Resolution', 400);

close(fig);



%% 资金变化

fig = figure( ...
    'Color', 'w', ...
    'Position', [120, 100, 1100, 650]);

ax = axes(fig);
hold(ax, 'on');


plot(ax, ...
    daily.Day, ...
    daily.CashLeft, ...
    '-o', ...
    'Color', moneyColor, ...
    'LineWidth', 2.1, ...
    'MarkerSize', 6, ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', moneyColor);


xlabel(ax, ...
    '日期', ...
    'FontName', fontName, ...
    'FontSize', 11);


ylabel(ax, ...
    '剩余现金（元）', ...
    'FontName', fontName, ...
    'FontSize', 11);


title(ax, ...
    '第三关保证型策略执行过程中的现金变化', ...
    'FontName', fontName, ...
    'FontSize', 14, ...
    'FontWeight', 'bold');


grid(ax, 'on');
box(ax, 'off');

ax.GridColor = [0.82, 0.84, 0.86];
ax.GridAlpha = 0.45;
ax.FontName = fontName;
ax.FontSize = 10;

xticks(ax, unique(daily.Day));

xlim(ax, ...
    [min(daily.Day), max(daily.Day)]);


cashValues = daily.CashLeft;

cashMin = min(cashValues);
cashMax = max(cashValues);


% 若现金全程不变，主动扩大纵轴，避免9190附近的异常放大
if abs(cashMax - cashMin) < 1e-9

    padding = max(100, 0.02 * abs(cashMin));

    ylim(ax, ...
        [cashMin - padding, ...
         cashMax + padding]);


    text(ax, ...
        mean(daily.Day), ...
        cashMin + 0.32 * padding, ...
        sprintf('全程现金保持 %.0f 元不变', cashMin), ...
        'FontName', fontName, ...
        'FontSize', 10, ...
        'Color', [0.24, 0.30, 0.34], ...
        'HorizontalAlignment', 'center', ...
        'BackgroundColor', 'w', ...
        'Margin', 2);

else

    cashRange = cashMax - cashMin;

    ylim(ax, ...
        [cashMin - 0.10 * cashRange, ...
         cashMax + 0.10 * cashRange]);

end


hold(ax, 'off');


exportgraphics(fig, ...
    fullfile( ...
    figureDir, ...
    'case3_worst_money_change.png'), ...
    'Resolution', 400);

close(fig);

end