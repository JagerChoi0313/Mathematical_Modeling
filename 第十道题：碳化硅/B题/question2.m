%% =========================================================
%                     本地函数
%% =========================================================


function res = solve_one( ...
    data, ...
    angle, ...
    smooth_num, ...
    min_dist, ...
    min_prom, ...
    fit_min, ...
    calc_min, ...
    calc_max)

%% 数据清洗

sigma = data(:,1);
R = data(:,2);

id = isfinite(sigma) & isfinite(R);

sigma = sigma(id);
R = R(id);

[sigma,id] = sort(sigma);
R = R(id);

if ~isempty(R) && R(1)==0
    sigma(1) = [];
    R(1) = [];
end

%% 截取分析区域

id = sigma >= fit_min;

x = sigma(id);
y = R(id);

%% 101点中心移动平均

ys = movmean( ...
    y, ...
    smooth_num, ...
    'Endpoints','shrink');

%% 建立三次样条函数

pp = spline(x,ys);

%% 初步寻找峰谷

[~,rough_peak] = main_peaks( ...
    x, ...
    ys, ...
    min_dist, ...
    min_prom);

[~,rough_valley] = main_peaks( ...
    x, ...
    -ys, ...
    min_dist, ...
    min_prom);

%% 利用样条曲线精确定位峰谷

[peak_x,peak_y] = refine_points( ...
    pp, ...
    x, ...
    rough_peak, ...
    min_dist, ...
    1);

[valley_x,valley_y] = refine_points( ...
    pp, ...
    x, ...
    rough_valley, ...
    min_dist, ...
    -1);

%% 去除过近重复极值

[peak_x,peak_y] = unique_close( ...
    peak_x, ...
    peak_y, ...
    1);

[valley_x,valley_y] = unique_close( ...
    valley_x, ...
    valley_y, ...
    -1);

%% 构造上下包络的公共有效区间

lo = max( ...
    min(peak_x), ...
    min(valley_x));

hi = min( ...
    max(peak_x), ...
    max(valley_x));

ngrid = linspace( ...
    max(lo,fit_min), ...
    hi, ...
    2500)';

%% 上下包络线

rmax_grid = interp1( ...
    peak_x, ...
    peak_y/100, ...
    ngrid, ...
    'pchip');

rmin_grid = interp1( ...
    valley_x, ...
    valley_y/100, ...
    ngrid, ...
    'pchip');

%% 根据两光束上下包络反演折射率

n_grid = refractive_index( ...
    rmax_grid, ...
    rmin_grid);

%% 选择稳定波段内的峰谷

pk = ...
    peak_x >= calc_min & ...
    peak_x <= calc_max;

vk = ...
    valley_x >= calc_min & ...
    valley_x <= calc_max;

sx = [ ...
    peak_x(pk); ...
    valley_x(vk)];

stype = [ ...
    ones(sum(pk),1); ...
    -ones(sum(vk),1)];

sy = [ ...
    peak_y(pk); ...
    valley_y(vk)];

%% 按波数排序

[sx,id] = sort(sx);

stype = stype(id);
sy = sy(id);

%% 保证峰谷交替

[sx,stype,sy] = make_alternating( ...
    sx, ...
    stype, ...
    sy);

%% 在极值位置求上下包络

rmax = interp1( ...
    peak_x, ...
    peak_y/100, ...
    sx, ...
    'pchip');

rmin = interp1( ...
    valley_x, ...
    valley_y/100, ...
    sx, ...
    'pchip');

%% 每个极值位置对应的折射率

nx = refractive_index( ...
    rmax, ...
    rmin);

%% 构造所有N>=1的极值组合

pair_sigma1 = [];
pair_n1 = [];

pair_sigma2 = [];
pair_n2 = [];

pair_N = [];
pair_d = [];

m = length(sx);

for i = 1:m-2

    % j=i+1 对应 N=0.5，因此从 i+2 开始
    for j = i+2:m

        N = (j-i)/2;

        g1 = ...
            sx(i) * ...
            sqrt( ...
            nx(i)^2 - ...
            sind(angle)^2);

        g2 = ...
            sx(j) * ...
            sqrt( ...
            nx(j)^2 - ...
            sind(angle)^2);

        den = 2*(g2-g1);

        if den > 0

            % cm 转换为 um
            d_um = ...
                N/den * 1e4;

            if ...
                isfinite(d_um) && ...
                d_um > 0

                pair_sigma1(end+1,1) = sx(i);
                pair_n1(end+1,1) = nx(i);

                pair_sigma2(end+1,1) = sx(j);
                pair_n2(end+1,1) = nx(j);

                pair_N(end+1,1) = N;
                pair_d(end+1,1) = d_um;

            end
        end
    end
end

%% 保存78组厚度结果

pair_table = table( ...
    pair_sigma1, ...
    pair_n1, ...
    pair_sigma2, ...
    pair_n2, ...
    pair_N, ...
    pair_d, ...
    'VariableNames',{ ...
    'sigma1_cm_1', ...
    'n1', ...
    'sigma2_cm_1', ...
    'n2', ...
    'N', ...
    'd_um'});

%% 保存有效极值

type_name = strings(length(sx),1);

type_name(stype==1) = "峰";
type_name(stype==-1) = "谷";

extrema_table = table( ...
    sx, ...
    type_name, ...
    sy, ...
    nx, ...
    'VariableNames',{ ...
    'sigma_cm_1', ...
    'Type', ...
    'Reflectance_percent', ...
    'n'});

%% 保存全部结果

res.angle = angle;

res.sigma = x;
res.raw = y;
res.smooth = ys;

res.peak_x = peak_x;
res.peak_y = peak_y;

res.valley_x = valley_x;
res.valley_y = valley_y;

res.n_sigma = ngrid;
res.n_curve = n_grid;

res.extrema_table = extrema_table;
res.pair_table = pair_table;

res.mean_d = mean(pair_d);
res.std_d = std(pair_d);
res.median_d = median(pair_d);

res.cv_d = ...
    res.std_d / ...
    res.mean_d * 100;

end


%% =========================================================
% 折射率反演
%% =========================================================

function n = refractive_index(rmax,rmin)

% 防止插值产生极小负数
rmax = max(rmax,0);
rmin = max(rmin,0);

% 两光束极值模型
A = ...
    ( ...
    sqrt(rmax) + ...
    sqrt(rmin) ...
    ) / 2;

% 防止分母为0
A = min(A,0.999999);

% Fresnel关系
n = ...
    (1+A) ./ ...
    (1-A);

end


%% =========================================================
% 初步峰值识别
%% =========================================================

function [py,px] = main_peaks( ...
    x, ...
    y, ...
    min_dist, ...
    min_prom)

x = x(:);
y = y(:);

%% 局部极大值候选

cand = find( ...
    y(2:end-1) > y(1:end-2) & ...
    y(2:end-1) >= y(3:end)) + 1;

if isempty(cand)

    py = [];
    px = [];

    return
end

%% 将波数间隔换算为数据点窗口

dx = median(diff(x));

w = max( ...
    round(min_dist/dx), ...
    1);

prom = zeros(size(cand));

%% 计算显著度

for k = 1:length(cand)

    i = cand(k);

    L = max(1,i-w);
    U = min(length(y),i+w);

    left_min = min(y(L:i));
    right_min = min(y(i:U));

    prom(k) = ...
        y(i) - ...
        max(left_min,right_min);

end

%% 删除显著度过低的点

keep = ...
    prom >= min_prom;

cand = cand(keep);
prom = prom(keep);

if isempty(cand)

    py = [];
    px = [];

    return
end

%% 最小峰距筛选

selected = cand(1);
selected_prom = prom(1);

for k = 2:length(cand)

    i = cand(k);

    if ...
        x(i)-x(selected(end)) ...
        >= min_dist

        selected(end+1,1) = i;
        selected_prom(end+1,1) = prom(k);

    elseif ...
        prom(k) > ...
        selected_prom(end)

        selected(end) = i;
        selected_prom(end) = prom(k);

    end
end

px = x(selected);
py = y(selected);

end


%% =========================================================
% 三次样条极值精化
%% =========================================================

function [xr,yr] = refine_points( ...
    pp, ...
    x, ...
    rough_x, ...
    min_dist, ...
    mode)

rough_x = rough_x(:);

xr = zeros(size(rough_x));
yr = zeros(size(rough_x));

for k = 1:length(rough_x)

    a = max( ...
        x(1), ...
        rough_x(k)-min_dist/2);

    b = min( ...
        x(end), ...
        rough_x(k)+min_dist/2);

    if mode==1

        % 极大值转化为负函数的极小值
        fun = @(z) -ppval(pp,z);

    else

        fun = @(z) ppval(pp,z);

    end

    xr(k) = golden_min( ...
        fun, ...
        a, ...
        b, ...
        1e-7, ...
        150);

    yr(k) = ...
        ppval(pp,xr(k));

end

[xr,id] = sort(xr);
yr = yr(id);

end


%% =========================================================
% 黄金分割搜索
%% =========================================================

function xmin = golden_min( ...
    fun, ...
    a, ...
    b, ...
    tol, ...
    maxiter)

phi = ...
    (sqrt(5)-1)/2;

c = ...
    b - ...
    phi*(b-a);

d = ...
    a + ...
    phi*(b-a);

fc = fun(c);
fd = fun(d);

for k = 1:maxiter

    if abs(b-a) < tol
        break
    end

    if fc < fd

        b = d;

        d = c;
        fd = fc;

        c = ...
            b - ...
            phi*(b-a);

        fc = fun(c);

    else

        a = c;

        c = d;
        fc = fd;

        d = ...
            a + ...
            phi*(b-a);

        fd = fun(d);

    end
end

xmin = ...
    (a+b)/2;

end


%% =========================================================
% 删除重复极值
%% =========================================================

function [x2,y2] = unique_close( ...
    x, ...
    y, ...
    mode)

[x,id] = sort(x(:));
y = y(id);

if isempty(x)

    x2 = x;
    y2 = y;

    return
end

x2 = x(1);
y2 = y(1);

for k = 2:length(x)

    if ...
        x(k)-x2(end) < 2

        if ...
            (mode==1 && y(k)>y2(end)) || ...
            (mode==-1 && y(k)<y2(end))

            x2(end) = x(k);
            y2(end) = y(k);

        end

    else

        x2(end+1,1) = x(k);
        y2(end+1,1) = y(k);

    end
end

end


%% =========================================================
% 保证峰谷交替
%% =========================================================

function [x2,t2,y2] = make_alternating( ...
    x, ...
    t, ...
    y)

x = x(:);
t = t(:);
y = y(:);

x2 = x(1);
t2 = t(1);
y2 = y(1);

for k = 2:length(x)

    if t(k) ~= t2(end)

        x2(end+1,1) = x(k);
        t2(end+1,1) = t(k);
        y2(end+1,1) = y(k);

    else

        if t(k)==1

            % 连续两个峰时保留更高的
            if y(k)>y2(end)

                x2(end) = x(k);
                y2(end) = y(k);

            end

        else

            % 连续两个谷时保留更低的
            if y(k)<y2(end)

                x2(end) = x(k);
                y2(end) = y(k);

            end

        end
    end
end

end


