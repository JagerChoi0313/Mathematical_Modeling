%% =========================================================
% 自定义百分位数
%% =========================================================

function q = my_percentile(x,p)

x = sort(x(:));

n = length(x);

if n==1

    q = x;

    return
end

pos = ...
    1 + ...
    (n-1)*p/100;

i = floor(pos);
j = ceil(pos);

if i==j

    q = x(i);

else

    q = ...
        x(i) + ...
        (pos-i) * ...
        (x(j)-x(i));

end

end