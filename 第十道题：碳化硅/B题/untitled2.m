%% 图5-1 两光束薄膜干涉光路示意图
clear;
clc;
close all;

figure('Color','w','Position',[200 100 950 650]);
hold on;

%% =========================
% 1. 绘制介质分界面
% ==========================

% 外延层上表面
plot([0 10],[6 6],'k-','LineWidth',2);

% 外延层与衬底界面
plot([0 10],[2 2],'k-','LineWidth',2);

% 填充外延层区域
patch([0 10 10 0],[2 2 6 6],...
      [0.93 0.95 1.00],...
      'EdgeColor','none',...
      'FaceAlpha',0.7);

% 填充衬底区域
patch([0 10 10 0],[-1 -1 2 2],...
      [0.90 0.90 0.90],...
      'EdgeColor','none',...
      'FaceAlpha',0.7);

% 重新绘制边界
plot([0 10],[6 6],'k-','LineWidth',2);
plot([0 10],[2 2],'k-','LineWidth',2);


%% =========================
% 2. 绘制入射光
% ==========================

% 入射点
P1 = [4 6];

% 入射光起点
P0 = [2 9];

quiver(P0(1),P0(2),...
       P1(1)-P0(1),P1(2)-P0(2),...
       0,...
       'Color',[0 0.35 0.75],...
       'LineWidth',2,...
       'MaxHeadSize',0.18);


%% =========================
% 3. 绘制第一束反射光
% ==========================

% 上表面直接反射
P2 = [6 9];

quiver(P1(1),P1(2),...
       P2(1)-P1(1),P2(2)-P1(2),...
       0,...
       'Color',[0.80 0.15 0.15],...
       'LineWidth',2,...
       'MaxHeadSize',0.18);


%% =========================
% 4. 绘制第二束光
% ==========================

% 进入外延层
P3 = [6 2];

quiver(P1(1),P1(2),...
       P3(1)-P1(1),P3(2)-P1(2),...
       0,...
       'Color',[0.10 0.50 0.20],...
       'LineWidth',2,...
       'MaxHeadSize',0.15);

% 在衬底界面反射后向上传播
P4 = [8 6];

quiver(P3(1),P3(2),...
       P4(1)-P3(1),P4(2)-P3(2),...
       0,...
       'Color',[0.10 0.50 0.20],...
       'LineWidth',2,...
       'MaxHeadSize',0.15);

% 透射出外延层
P5 = [9.4 8.2];

quiver(P4(1),P4(2),...
       P5(1)-P4(1),P5(2)-P4(2),...
       0,...
       'Color',[0.10 0.50 0.20],...
       'LineWidth',2,...
       'MaxHeadSize',0.18);


%% =========================
% 5. 绘制法线
% ==========================

plot([4 4],[4.8 8.3],'k--','LineWidth',1.2);


%% =========================
% 6. 标记入射角 alpha
% ==========================

r = 0.9;

% 从竖直法线到入射光方向的示意圆弧
phi = linspace(90,124,60);

x_arc = P1(1) + r*cosd(phi);
y_arc = P1(2) + r*sind(phi);

plot(x_arc,y_arc,'k-','LineWidth',1.2);

text(3.35,7.05,'$\alpha$',...
    'Interpreter','latex',...
    'FontSize',16);


%% =========================
% 7. 标记折射角 theta
% ==========================

r2 = 0.85;

phi2 = linspace(270,296.5,60);

x_arc2 = P1(1) + r2*cosd(phi2);
y_arc2 = P1(2) + r2*sind(phi2);

plot(x_arc2,y_arc2,'k-','LineWidth',1.2);

text(4.25,5.05,'$\theta$',...
    'Interpreter','latex',...
    'FontSize',16);


%% =========================
% 8. 标记外延层厚度 d
% ==========================

x_d = 1.0;

plot([x_d x_d],[2.15 5.85],'k-','LineWidth',1.3);

% 上下箭头
plot(x_d,5.85,'k^','MarkerFaceColor','k','MarkerSize',7);
plot(x_d,2.15,'kv','MarkerFaceColor','k','MarkerSize',7);

text(0.62,4,'$d$',...
    'Interpreter','latex',...
    'FontSize',17);


%% =========================
% 9. 添加文字标注
% ==========================

text(0.4,8.4,'空气',...
    'FontSize',15);

text(0.4,4.1,'碳化硅外延层',...
    'FontSize',15);

text(0.4,0.5,'衬底',...
    'FontSize',15);

text(1.65,8.9,'入射光',...
    'FontSize',13,...
    'Color',[0 0.35 0.75]);

text(5.55,8.75,'光束1：上表面反射光',...
    'FontSize',12,...
    'Color',[0.80 0.15 0.15]);

text(6.15,3.45,'光束2',...
    'FontSize',12,...
    'Color',[0.10 0.50 0.20]);

text(5.85,1.55,'外延层—衬底界面',...
    'FontSize',12);


%% =========================
% 10. 图形格式设置
% ==========================

axis equal;
axis([0 10 -0.5 10]);
axis off;

title('图5-1  两光束薄膜干涉光路示意图',...
      'FontSize',16,...
      'FontWeight','normal');

set(gca,'FontSize',12);

%% =========================
% 11. 保存图片
% ==========================

exportgraphics(gcf,...
    '图5-1_两光束薄膜干涉光路示意图.png',...
    'Resolution',300);